# Дано целое положительно число. Проверить истинность высказывания: "Данное число является нечетным трехзначным"
while True:
    n = input("Введите целое положительное трехзначное число: ")
    try:
        n = int(n)
        if 100 <= n <= 999:
            break
        else:
            print("Ошибка: Число должно быть строго трехзначным!")
    except ValueError:
        print("Ошибка: Неправильно ввели! Нужно ввести целое число.")
if n % 2 != 0:
    print("Правда")
else:
    print("Ложь")
# Даны три числа. Найти среднее из них (то есть то число, расположенное между наименьшим и наибольшим)
a = 50
b = 24
c = 95
if (b <= a <= c) or (c <= a <= b):
    middle = a
elif (a <= b <= c) or (c <= a <= b):
    middle = b
else:
    middle = c
print("Исходные числа:", a, b, c)
print ("Среднее число =", middle)
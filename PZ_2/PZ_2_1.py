# Дано трехзначное число.
# В нем зачеркнули первую слева цифру и приписали ее справа.
# Вывести полученное число.
number = input("Дано трехзначное число: ")

while not number.isnumeric() or len(number) != 3:
    print("Ошибка. Число должно быть трехзначным, без букв и символов")
    number = input("Дано трехзначное число: ")

result = number[1:] + number[0]
print(result)